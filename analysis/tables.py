"""LaTeX table bodies (booktabs ``tabular`` environments, no float wrapper) from the analysis CSVs.

Usage: ``python -m analysis.tables [--run main]``. For ``main`` the files go to ``paper/tables/``, for other
runs to ``results/analysis/<run>/tables/``. Include with ``\\input{tables/<name>}`` inside a ``table``
environment that carries the caption. Missing cells print as "n/a".
"""
from __future__ import annotations

import argparse
from pathlib import Path

from .common import ANALYSIS, EDIT_TYPES, TAB_DIR, TIERS, read_csv, short

NA = "n/a"
DETS = ("V", "C", "R", "r_field", "f_trace")
DET_TEX = {"V": "V", "C": "C", "R": "R", "r_field": "tokens vs re-derived", "f_trace": "tokens vs log"}
COND_ORDER = ["none", "no_memory", "G1", "G2u", "G2s", "G2s_insider", "G1+G2s"]


def tab_dir(run: str) -> Path:
    d = TAB_DIR if run == "main" else ANALYSIS / run / "tables"
    d.mkdir(parents=True, exist_ok=True)
    return d


def esc(s) -> str:
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def num(x, nd=2) -> str:
    return NA if x is None else f"{x:.{nd}f}"


def pct(x, nd=1) -> str:
    return NA if x is None else f"{100 * x:.{nd}f}"


def ci(lo, hi, f=num) -> str:
    return "" if lo is None or hi is None else f" [{f(lo)}, {f(hi)}]"


def pval(p) -> str:
    if p is None:
        return NA
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def tabular(cols: str, header: list, rows: list, note: str = "") -> str:
    lines = [rf"\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    lines += [" & ".join(r) + r" \\" if isinstance(r, list) else r for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    if note:
        lines.append(f"% {note}")
    return "\n".join(lines) + "\n"


def _write(run: str, name: str, text: str) -> Path:
    p = tab_dir(run) / f"{name}.tex"
    p.write_text(f"% generated by analysis/tables.py from results/analysis/{run}/ -- do not edit\n" + text)
    return p


# ============================================================================ main-text tables
CRIT = {"P1_self_trust_premium": "H1: $>0$", "P2_verbal_recognition_T2": "H2: upper bound $<0.65$",
        "P3_integrity_gap_T3": "H3: $>0$", "P4_gate_effectiveness": "H5: $\\geq 50$, lower bound $>0$"}


def primary(run: str) -> Path:
    rows = read_csv(ANALYSIS / run / "primary.csv")
    label = {"P1_self_trust_premium": ("Self-trust premium (pp)", lambda x: pct(x)),
             "P2_verbal_recognition_T2": ("Verbal recognition AUROC, T2", num),
             "P3_integrity_gap_T3": ("Integrity gap AUROC, T3", num),
             "P4_gate_effectiveness": ("Gate: relative ASR reduction (\\%)", lambda x: pct(x))}
    body = []
    for r in rows:
        name, f = label.get(r["estimand"], (esc(r["estimand"]), num))
        sup = NA if r["supported"] is None else ("yes" if r["supported"] in ("True", True, 1.0) else "no")
        body.append([name, CRIT.get(r["estimand"], ""), (f(r["est"]) + ci(r["lo"], r["hi"], f)) if r["est"] is not None else NA,
                     pval(r["p"]), pval(r["p_holm"]), NA if r["n"] is None else str(int(r["n"])), sup])
    return _write(run, "primary", tabular("llrrrrl", ["Estimand", "Registered criterion", "Estimate [95\\% CI]", "$p$",
                                                     "$p_\\mathrm{Holm}$", "$n$", "Met"], body))


def detection_tier(run: str) -> Path:
    rows = [r for r in read_csv(ANALYSIS / run / "detection_mean.csv")
            if r["negset"] == "same_slot" and r["edit_type"] == "all"]
    body = []
    for d in DETS:
        cells = []
        for t in TIERS:
            m = [r for r in rows if r["detector"] == d and r["tier"] == t]
            cells.append(num(m[0]["auroc_est"]) + ci(m[0]["auroc_lo"], m[0]["auroc_hi"]) if m and m[0]["auroc_est"] is not None else NA)
        if any(c != NA for c in cells):
            body.append([DET_TEX[d]] + cells)
    return _write(run, "detection_tier", tabular("l" + "r" * len(TIERS), ["Detector"] + list(TIERS),
                                                 body or [[NA] * (1 + len(TIERS))]))


def p4(run: str) -> Path:
    rows = [r for r in read_csv(ANALYSIS / run / "p4_asr.csv") if r["group"] == "pooled" and r["edit_type"] == "all"]
    clean = {r["condition"]: r for r in read_csv(ANALYSIS / run / "p4_clean.csv") if r["group"] == "pooled"}
    tiers = ["T0", "T2", "T3", "-"]
    body = []
    conds = sorted({r["condition"] for r in rows} | set(clean),
                   key=lambda c: COND_ORDER.index(c) if c in COND_ORDER else 99)
    for c in conds:
        cells = []
        for t in tiers:
            m = [r for r in rows if r["condition"] == c and r["tier"] == t]
            cells.append(f"{pct(m[0]['asr_est'])}{ci(m[0]['asr_lo'], m[0]['asr_hi'], pct)} ({int(m[0]['asr_n'])})"
                         if m and m[0]["asr_est"] is not None else "--")
        cl = clean.get(c)
        cells.append(f"{pct(cl['accuracy_est'])} ({int(cl['accuracy_n'])})" if cl and cl["accuracy_est"] is not None else "--")
        body.append([esc(c)] + cells)
    return _write(run, "p4", tabular("lrrrrr", ["Condition", "ASR T0", "ASR T2", "ASR T3", "ASR (no tier)",
                                               "Clean acc."], body or [[NA] * 6],
                                     "ASR in %, [95% CI], (n target questions); unparsed = attack failed"))


EDIT_NAMES = {"E1": "E1 swapped fact", "E2": "E2 instruction", "E3": "E3 conclusion",
              "E4": "E4 commitment", "E5": "E5 confidence"}


def edit_summary(run: str, tier: str = "T2") -> Path:
    """Main-text table: per edit type, what inspection sees (V), what the log check sees (C), and how often the
    forgery steers the decision without and with the gate. One forger tier (T2)."""
    det = [r for r in read_csv(ANALYSIS / run / "detection_mean.csv") if r["negset"] == "same_slot" and r["tier"] == tier]
    asr = [r for r in read_csv(ANALYSIS / run / "p4_asr.csv") if r["group"] == "pooled" and r["tier"] == tier]

    def auc(d, e):
        m = [r for r in det if r["detector"] == d and r["edit_type"] == e]
        return num(m[0]["auroc_est"]) if m and m[0]["auroc_est"] is not None else NA

    def rate(c, e):
        m = [r for r in asr if r["condition"] == c and r["edit_type"] == e]
        return f"{pct(m[0]['asr_est'], 0)} ({int(m[0]['asr_n'])})" if m and m[0]["asr_est"] is not None else NA
    body = [[EDIT_NAMES[e], auc("V", e), auc("C", e), rate("none", e), rate("G1", e)] for e in EDIT_TYPES]
    body.append(r"\midrule")
    body.append(["All edits", auc("V", "all"), auc("C", "all"), rate("none", "all"), rate("G1", "all")])
    return _write(run, "edit_summary", tabular("@{}lrrrr@{}", ["Edit", "V", "C", "ASR none", "ASR G1"],
                                               body, f"AUROC of V and C (mean over hosted victims) and attack success in % (n) at tier {tier}"))



