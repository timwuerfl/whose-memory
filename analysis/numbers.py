"""Every number the paper may quote, as LaTeX macros, from ``results/analysis/<run>/hosted.json``.

Usage: ``python -m analysis.numbers [--run main]``. Writes ``paper/numbers.tex`` for ``main`` (for other runs
``results/analysis/<run>/numbers.tex``) and ``results/analysis/<run>/numbers_index.md`` (macro -> value ->
meaning). Macro names are camel case without digits (digits are spelled out: T2 -> TTwo). Formats:
percentages and percentage points with 1 decimal (no % sign; the text adds it), AUROC and other
probabilities-as-scores with 2 decimals, p-values with 3 decimals (or "<0.001"), counts as integers.
Each estimate X comes with XLo, XHi, XCI ("[lo, hi]"), XN and, where tested, XP. A value that cannot be
computed is "n/a". Negative numbers use ``\\ensuremath{-}`` so that macros work in text and math.
"""
