PREFIXES = ("Prim", "Pone", "Laund", "Det", "Afc", "Negs", "Judge", "Valid", "Tthree", "Pfour", "Gate", "Cost")
DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]
NA = "n/a"


def mname(*parts) -> str:
    """Camel-case macro name with digits spelled out and other characters removed."""
    out = ""
    for p in parts:
        s = re.sub(r"\d", lambda m: " " + DIGITS[int(m.group())] + " ", str(p))
        out += "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z]+", s) if w)
    return out


def _neg(s: str) -> str:
    return s.replace("-", r"\ensuremath{-}", 1) if s.startswith("-") else s


def f_pct(x) -> str:
    return NA if x is None else _neg(f"{100 * x:.1f}")


def f_auc(x) -> str:
    return NA if x is None else _neg(f"{x:.2f}")


def f_raw(x) -> str:
    return NA if x is None else _neg(f"{x:.1f}")


def f_p(p) -> str:
    return NA if p is None else (r"\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}")


def f_int(n) -> str:
    return NA if n is None else f"{int(n):,}".replace(",", "{,}")


class Macros:
    def __init__(self):
        self.items: dict = {}

    def add(self, name: str, value: str, meaning: str) -> None:
        if name in self.items:
            raise ValueError(f"duplicate macro {name}")
        self.items[name] = (value, meaning)

    def rec(self, name: str, rec, fmt, meaning: str) -> None:
        """Estimate plus Lo/Hi/CI/N (and P if tested) of a result record."""
        rec = rec if isinstance(rec, dict) else {}
        est = rec.get("est")
        lo, hi = (rec.get("ci") or [None, None])[:2]
        why = f" [n/a: {rec['reason']}]" if est is None and rec.get("reason") else ""
        self.add(name, fmt(est), meaning + why)
        self.add(name + "Lo", fmt(lo), meaning + ", lower 95% CI bound")
        self.add(name + "Hi", fmt(hi), meaning + ", upper 95% CI bound")
        self.add(name + "CI", NA if lo is None or hi is None else f"[{fmt(lo)}, {fmt(hi)}]", meaning + ", 95% CI")
        self.add(name + "N", f_int(rec.get("n")), meaning + ", n")
        self.add(name + "P", f_p(rec.get("p")), meaning + ", two-sided bootstrap p (n/a if not tested)")

    def ensure(self, name: str, meaning: str, record: bool = True) -> None:
        """Define a macro (with its CI variants if ``record``) as n/a unless the data already defined it, so
        the macro set does not depend on which cells have data yet."""
        if name in self.items:
            return
        if record:
            self.rec(name, {"reason": "no data yet"}, f_pct, meaning)
        else:
            self.add(name, NA, meaning + " [n/a: no data yet]")

    def tex(self, run: str) -> str:
        lines = [f"% generated by analysis/numbers.py from results/analysis/{run}/hosted.json -- do not edit",
                 f"% macro prefixes: {', '.join(PREFIXES)}"]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, (v, _) in self.items.items()]
        return "\n".join(lines) + "\n"

    def index(self, run: str) -> str:
        lines = [f"# Number macros ({run})", "", "| macro | value | meaning |", "|---|---|---|"]
        lines += [f"| `\\{k}` | {v.replace('|', '/')} | {m.replace('|', '/')} |" for k, (v, m) in self.items.items()]
        return "\n".join(lines) + "\n"


